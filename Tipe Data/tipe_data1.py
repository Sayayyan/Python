#Tipe data numerik: integer (bilangan bulat)
umur = 30
print ("Umur: ", umur, " Tipe data: ", type(umur))

#Tipe data numerik: float (bilangan bulat)
tinggi = 1.75
print("Tiinggi: ", tinggi, " Tipe data: ",type(tinggi))

#Tipe data string (teks)
nama = "Budi"
print("Nama: ", nama, " Tipe data ", type(nama))

#Tipe data boolean (benar atau salah)
apakah_lulus = True
print("Lulus: ", apakah_lulus, " Tipe data: ",type(apakah_lulus))

#Tipe data list (daftar yang bisa diubah)
buah = ["apel", "pisang", "mangga"]
print("Buah: ", buah, " Tipe data: ", type(buah))

#Tipe data tuple (daftar yang tidak bisa diubah)
koordinat = (10, 20)
print("Koordinat: ", koordinat, " Tipe data: ", type(koordinat))

#Tipe data set (kumpulan nilai unik)
nomor_unik = {1, 2, 2, 3, 4, 4, 5}
print("Nomor unik: ", nomor_unik, "Tipe data", type(nomor_unik))

#Tipe data dictionary (pasangan kunci-nilai)
profil = {"nama": "Budi: ", "Umur": 30}
print("Profil: ", profil, " Tipe data: ", type(profil))