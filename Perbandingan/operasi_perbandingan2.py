#operasi komparasi

#setiap hasil dari operasi komparasi adalah boolean

#>, <, >=, <=, ==, !=, is, is not

a = 4
b = 2

#Lebih besar dari >
print('========= lebih besar dari (>)')
hasil = a > 3
print(a, ' > ', 3, ' = ', hasil)
hasil = b > 3
print(b, ' > ', 3, ' = ', hasil)
hasil = b > 2
print(b, ' > ', 2, ' = ', hasil)

#Kurang dari <
print('========= Kurang dari (<)')
hasil = a < 3
print(a, ' < ', 3, ' = ', hasil)
hasil = b < 3
print(b, ' < ', 3, ' = ', hasil)
hasil = b < 2
print(b, ' < ', 2, ' = ', hasil)

#Lebih dari sama dengan >=
print('========= Lebih dari sama dengan (>=)')
hasil = a >= 3
print(a, ' >= ', 3, ' = ', hasil)
hasil = b >= 3
print(b, ' >= ', 3, ' = ', hasil)
hasil = b >= 2
print(b, ' >= ', 2, ' = ', hasil)

#Kurang dari sama dengan <=
print('========= Kurang dari sama dengan (<=)')
hasil = a <= 3
print(a, ' <= ', 3, ' = ', hasil)
hasil = b <= 3
print(b, ' <= ', 3, ' = ', hasil)
hasil = b <= 2
print(b, ' <= ', 2, ' = ', hasil)

#Sama dengan ==
print('========= Sama dengan (==)')
hasil = a == 4
print(a, ' == ', 4, ' = ', hasil)
hasil = b == 4
print(b, ' == ', 4, ' = ', hasil)

#Tidak sama dengan ==
print('========= Sama dengan (==)')
hasil = a != 4
print(a, ' != ', 4, ' = ', hasil)
hasil = b != 4
print(b, ' != ', 4, ' = ', hasil)