bilangan1 = float("Masukkan bilangan pertama : ")
bilangan2 = float("Masukkan bilangan kedua : ")
if bilangan1 == bilangan2:
    print("Kedua bilangan sama besar yaitu", bilangan1)
elif bilangan1 > bilangan2:
    print("Bilangan 1 adalah bilangan terbesar, yaitu", bilangan1)
else:
    print("Bilangan 2 adalah bilangan terbesar, yaitu", bilangan2)